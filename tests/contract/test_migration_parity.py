"""AC-5 migration parity between the SQLite and Postgres dialects.

The shared, store-tagged migration sequence (``_migrations.MIGRATIONS``) is the
single source of truth: the same version sequence, the same v1 -> v2 forward
upgrade, and the same column model must materialize on both dialects. The
offline arm proves this on rendered DDL and on a live SQLite database; the
Postgres arm (skipped cleanly when ``MNEMOSEED_TEST_PG_DSN`` is absent) mirrors
the same checks against a live server and compares the real catalogs.

Per PRD-08 the stores live in separate schemas (D6), so graph and meta never
share one ``schema_version`` table.
"""


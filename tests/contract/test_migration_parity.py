def test_sqlite_v1_to_head_forward_migration_preserves_data() -> None:
    """A real file at v1 upgrades to head: column added, every row survives."""
    graph, meta = _load_v1_sqlite()
    assert "pinned" not in _column_names(graph, "nodes")
    graph_before = _snapshot(graph, _GRAPH_TABLES)
    meta_before = _snapshot(meta, _META_TABLES)
    assert current_schema_version(graph, "graph") == 1
    assert current_schema_version(meta, "meta") == 1

    # forward migration: graph advances to 5, meta to 6 (v2/v5 are graph-only,
    # v6 is meta-only: identity users table + hashed token column)
    assert apply_migrations(graph, "graph") == 5
    assert apply_migrations(meta, "meta") == 6
    assert current_schema_version(graph, "graph") == 5
    assert current_schema_version(meta, "meta") == 6

    assert "pinned" in _column_names(graph, "nodes")
    assert "promotion_status" in _column_names(graph, "nodes")
    row = dict(
        graph.execute("SELECT pinned, promotion_status, payload FROM nodes WHERE node_id = 'mv1'").fetchone()
    )
    assert row["pinned"] == 0  # NOT NULL DEFAULT 0 backfills the existing row
    assert row["promotion_status"] == "promoted"  # v5 default back-compat on the same row
    assert json.loads(row["payload"]) == make_pref(node_id="mv1").props  # byte-identical payload

    graph_after = _snapshot(graph, _GRAPH_TABLES)
    meta_after = _snapshot(meta, _META_TABLES)
    assert _project_without_deltas(graph_after["nodes"]) == graph_before["nodes"]
    for table in ("node_versions", "edges"):
        assert graph_after[table] == graph_before[table], f"row drift in {table} across v1->v3"
    for table in _META_TABLES:
        # v6 adds the nullable token_hash column; the legacy v1 token row is
        # preserved byte-for-byte, projected without the new (empty) column.
        rows = [r for r in meta_after[table]]
        if table == "tokens":
            rows = [{k: v for k, v in r.items() if k != "token_hash"} for r in rows]
        assert rows == meta_before[table], f"row drift in {table} across v1->head"

    # v3 supersedes the legacy score_pool: the new per-profile table exists,
    # empty (no data migration), and the old singleton row is untouched.
    assert _column_names(meta, "profile_score_pool") == [
        "profile_id",
        "balance",
        "watermark_start",
        "watermark_end",
        "last_event_start",
        "last_event_end",
    ]
    empty = meta.execute("SELECT COUNT(*) FROM profile_score_pool").fetchone()
    assert int(empty[0]) == 0
    legacy = dict(meta.execute("SELECT id, balance FROM score_pool").fetchone())
    assert legacy["id"] == 1
    assert legacy["balance"] == 0.0

    # v4 dream_token_ledger exists, empty (no backfill: it is born empty)
    assert _column_names(meta, "dream_token_ledger") == ["profile_id", "year_month", "tokens"]
    unique_constraint = meta.execute(
        "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'dream_token_ledger'"
    ).fetchone()
    assert "UNIQUE (profile_id, year_month)" in unique_constraint[0]

    # v6 identity: the users table exists (empty after upgrade — no backfill),
    # and the legacy tokens row gained a nullable token_hash (NULL for v1 era).
    assert _column_names(meta, "users") == ["user_id", "username", "password_hash", "role", "created_at"]
    user_row = dict(meta.execute("SELECT token_hash FROM tokens WHERE token_id = 'tok-1'").fetchone())
    assert user_row["token_hash"] is None  # pre-v6 tokens hold no hash (blessed empty)

    # tracker advanced one step per graph/meta delta (v2/v5 graph, v4/v6 meta)
    graph_versions = [int(r[0]) for r in graph.execute(f"SELECT version FROM {SCHEMA_VERSION_TABLE}")]
    meta_versions = [int(r[0]) for r in meta.execute(f"SELECT version FROM {SCHEMA_VERSION_TABLE}")]
    assert sorted(graph_versions) == [1, 2, 5]
    assert sorted(meta_versions) == [1, 3, 4, 6]


def _project_without_deltas(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    """Drop the post-v1 migration delta columns (pinned v2, promotion_status v5)."""
    deltas = {"pinned", "promotion_status"}
    return [{k: v for k, v in row.items() if k not in deltas} for row in rows]


# -------------------------------------------------------------- postgres arm (live)


def _pg_conn(dsn: str) -> Any:
    return psycopg.connect(dsn, row_factory=dict_row)


def _pg_insert(conn: Any, schema: str, table: str, row: dict[str, object]) -> None:
    columns = ", ".join(row)
    placeholders = ", ".join("%s" for _ in row)
    conn.execute(
        f"INSERT INTO {schema}.{table} ({columns}) VALUES ({placeholders})",
        list(row.values()),
    )


def _pg_snapshot(conn: Any, schema: str, table: str) -> list[dict[str, object]]:
    return [dict(r) for r in conn.execute(f"SELECT * FROM {schema}.{table}").fetchall()]


def test_postgres_v1_to_head_forward_migration_preserves_data() -> None:
    """Live Postgres mirrors the sqlite arm: v1 data survives the head upgrade."""
    dsn = require_pg()
    graph_schema = f"par_g_{uuid.uuid4().hex[:8]}"
    meta_schema = f"par_m_{uuid.uuid4().hex[:8]}"
    conn = _pg_conn(dsn)

    with conn.transaction():
        assert apply_postgres_migrations(conn, "graph", target=1, schema=graph_schema) == 1
        assert apply_postgres_migrations(conn, "meta", target=1, schema=meta_schema) == 1
        assert current_postgres_schema_version(conn, "graph", schema=graph_schema) == 1
        assert "pinned" not in [c["column_name"] for c in _pg_columns(conn, graph_schema, "nodes")]

        node = make_pref(node_id="mv1", entities=["ui", "theme"])
        node_row = _node_row_mirror(node)
        _pg_insert(conn, graph_schema, "nodes", node_row)
        _pg_insert(
            conn,
            graph_schema,
            "node_versions",
            {
                "node_id": "mv1",
                "version": 1,
                "profile_id": node.profile_id,
                "valid_from": iso8601_utc(node.valid_from),
                "valid_to": None,
                "superseded_by": None,
                "changed_at": iso8601_utc(node.updated_at),
                "payload": json.dumps(node.props),
            },
        )
        before_nodes = _pg_snapshot(conn, graph_schema, "nodes")

        assert apply_postgres_migrations(conn, "graph", schema=graph_schema) == 5
        assert apply_postgres_migrations(conn, "meta", schema=meta_schema) == 6
        assert current_postgres_schema_version(conn, "graph", schema=graph_schema) == 5
        assert current_postgres_schema_version(conn, "meta", schema=meta_schema) == 6
        pool_columns = [c["column_name"] for c in _pg_columns(conn, meta_schema, "profile_score_pool")]
        assert pool_columns == [
            "profile_id",
            "balance",
            "watermark_start",
            "watermark_end",
            "last_event_start",
            "last_event_end",
        ]
        empty = conn.execute("SELECT COUNT(*) AS n FROM " + meta_schema + ".profile_score_pool").fetchone()
        assert empty is not None and int(empty["n"]) == 0
        ledger_columns = [c["column_name"] for c in _pg_columns(conn, meta_schema, "dream_token_ledger")]
        assert ledger_columns == ["profile_id", "year_month", "tokens"]
        user_columns = [c["column_name"] for c in _pg_columns(conn, meta_schema, "users")]
        assert user_columns == ["user_id", "username", "password_hash", "role", "created_at"]
        token_hash_columns = [c["column_name"] for c in _pg_columns(conn, meta_schema, "tokens")]
        assert "token_hash" in token_hash_columns

        columns = [c["column_name"] for c in _pg_columns(conn, graph_schema, "nodes")]
        assert "pinned" in columns
        assert "promotion_status" in columns
        after_nodes = _pg_snapshot(conn, graph_schema, "nodes")
        assert [
            {k: v for k, v in r.items() if k not in ("pinned", "promotion_status")} for r in after_nodes
        ] == before_nodes
        preserved = after_nodes[0]
        assert preserved["pinned"] == 0
        assert preserved["promotion_status"] == "promoted"
        clean_payload = preserved["payload"]
        if isinstance(clean_payload, str):  # sqlite TEXT arm
            clean_payload = json.loads(clean_payload)
        assert clean_payload == node.props


def _neutral_head_columns() -> dict[str, list[Column]]:
    """Neutral columns each table must have at head: CreateTable base plus the
    AddColumn deltas that later migrations apply (pinned v2 and
    promotion_status v5 on graph.nodes)."""
    columns_by_table: dict[str, list[Column]] = {}
    for migration in MIGRATIONS:
        for op in migration.ops:
            if isinstance(op, CreateTable):
                columns_by_table.setdefault(op.name, []).extend(op.columns)
            elif isinstance(op, AddColumn):
                columns_by_table.setdefault(op.table, []).append(op.column)
    return columns_by_table


def test_live_catalog_zero_diff_against_shared_ops() -> None:
    """Introspect the real catalogs; both match the neutral column spec (zero diff)."""
    dsn = require_pg()
    graph_db = sqlite3.connect(":memory:", isolation_level=None)  # store isolation (D6)
    graph_db.row_factory = sqlite3.Row
    meta_db = sqlite3.connect(":memory:", isolation_level=None)
    meta_db.row_factory = sqlite3.Row
    apply_migrations(graph_db, "graph")
    apply_migrations(meta_db, "meta")

    graph_schema = f"par_g_{uuid.uuid4().hex[:8]}"
    meta_schema = f"par_m_{uuid.uuid4().hex[:8]}"
    conn = _pg_conn(dsn)
    with conn.transaction():
        apply_postgres_migrations(conn, "graph", schema=graph_schema)
        apply_postgres_migrations(conn, "meta", schema=meta_schema)

    for table_name, columns in _neutral_head_columns().items():
        emb = graph_db if table_name in set(_GRAPH_TABLES) else meta_db
        target_pg = graph_schema if table_name in set(_GRAPH_TABLES) else meta_schema
        sqlite_cols = {
            (str(c[1]).strip('"'), bool(c[3]), bool(c[5]))  # (name, notnull, pk)
            for c in emb.execute(f"PRAGMA table_info({table_name})").fetchall()
        }
        pg_cols = {
            (str(c["column_name"]), c["is_nullable"] == "NO", c["has_pk"])
            for c in _pg_columns(conn, target_pg, table_name)
        }
        expected = {(col.name, col.not_null, bool(col.primary_key)) for col in columns}
        # sqlite reports exactly the declared flags; Postgres makes every PK
        # physically NOT NULL (identity polls additionally turn NOT NULL on).
        expected_pg = {
            (col.name, col.not_null or bool(col.primary_key), bool(col.primary_key)) for col in columns
        }
        assert sqlite_cols == expected, f"sqlite {table_name} diverges from neutral ops"
        assert pg_cols == expected_pg, f"postgres {table_name} diverges from neutral ops"


def _pg_columns(conn: Any, schema: str, table: str) -> list[dict[str, object]]:
    columns = [
        dict(r)
        for r in conn.execute(
            "SELECT column_name, data_type, is_nullable, column_default "
            "FROM information_schema.columns "
            "WHERE table_schema = %s AND table_name = %s ORDER BY ordinal_position",
            (schema, table),
        ).fetchall()
    ]
    pk_names = {
        str(r["attname"])
        for r in conn.execute(
            "SELECT a.attname FROM pg_index i "
            "JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) "
            "WHERE i.indrelid = %s::regclass AND i.indisprimary",
            (f"{schema}.{table}",),
        ).fetchall()
    }
    return [dict(col, has_pk=col["column_name"] in pk_names) for col in columns]

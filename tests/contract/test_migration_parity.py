# ---------------------------------------------------------------- ddl parsing


def _table_body(sql: str) -> str:
    """Body of a ``CREATE TABLE ... (...)`` statement (paren-depth aware)."""
    start = sql.index("(")
    depth = 0
    for i in range(start, len(sql)):
        if sql[i] == "(":
            depth += 1
        elif sql[i] == ")":
            depth -= 1
            if depth == 0:
                return sql[start + 1 : i]
    raise AssertionError(f"unbalanced CREATE TABLE: {sql}")


def _split_top_level(body: str) -> list[str]:
    clauses: list[str] = []
    current: list[str] = []
    depth = 0
    i = 0
    while i < len(body):
        ch = body[i]
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            clauses.append("".join(current).strip())
            current = []
            i += 1
            if i < len(body) and body[i] == " ":
                i += 1
            continue
        current.append(ch)
        i += 1
    if current:
        clauses.append("".join(current).strip())
    return clauses


def _parse_column_clause(clause: str) -> tuple[str, str, bool, bool, bool, bool]:
    """(name, kind, has_pk, has_not_null, has_default, has_references)."""
    upper = clause.upper()
    name, rest = clause.split(maxsplit=1)
    if "DOUBLE PRECISION" in upper:
        kind = "DOUBLE PRECISION"
    else:
        kind = rest.split(maxsplit=1)[0]
    has_pk = "PRIMARY KEY" in upper
    has_nn = "NOT NULL" in upper
    has_default = "DEFAULT" in upper and "GENERATED BY DEFAULT AS IDENTITY" not in upper
    has_ref = "REFERENCES" in upper
    return (name, kind, has_pk, has_nn, has_default, has_ref)


def _parse_create_table(sql: str) -> list[tuple[str, str, bool, bool, bool, bool]]:
    columns = (
        _parse_column_clause(cl)
        for cl in _split_top_level(_table_body(sql))
        if not cl.upper().startswith("UNIQUE")
    )
    return [c for c in columns if c]


def _parse_index(sql: str) -> tuple[bool, str, str, tuple[str, ...]]:
    match = re.search(r"CREATE (UNIQUE )?INDEX IF NOT EXISTS (\w+) ON (\w+) \(([^)]+)\)", sql)
    assert match is not None, sql
    unique, name, table, columns = match.groups()
    return bool(unique), name, table, tuple(part.strip() for part in columns.split(","))


# ------------------------------------------------------- shared-op schema parity


def _expected_sqlite_kind(kind: str) -> str:
    return _SQLITE_KINDS[kind]


def _expected_pg_kind(kind: str) -> str:
    return _PG_KINDS[kind]


def test_version_sequences_identical_on_both_dialects() -> None:
    """The dialect-agnostic sequence IS the parity baseline (graph 1,2,5; meta 1,3,4,6)."""
    assert latest_version() == 6
    graph_versions = sorted(m.version for m in MIGRATIONS if m.applies_to("graph"))
    meta_versions = sorted(m.version for m in MIGRATIONS if m.applies_to("meta"))
    assert graph_versions == [1, 2, 5]
    assert meta_versions == [1, 3, 4, 6]
    assert len(MIGRATIONS) == latest_version()


def test_create_tables_render_zero_diff_from_shared_ops() -> None:
    """Both dialects materialise the same column model; only the alias map differs."""
    for migration in MIGRATIONS:
        for op in migration.ops:
            if not isinstance(op, CreateTable):
                continue
            sqlite_cols = _parse_create_table(render_sqlite(op))
            pg_cols = _parse_create_table(render_postgres(op))
            assert len(sqlite_cols) == len(pg_cols) == len(op.columns)
            for index, column in enumerate(op.columns):
                s, p = sqlite_cols[index], pg_cols[index]
                # identity is the same neutral column, in the same position
                assert s[0] == p[0] == column.name
                # kind: each dialect lands exactly where its documented map sends it
                assert s[1] == _expected_sqlite_kind(column.kind)
                assert p[1] == _expected_pg_kind(column.kind)
                # dialect-independent flags agree between the two parses
                assert s[2] == p[2] == column.primary_key  # has pk
                assert s[3] == p[3] == column.not_null  # not null
                assert s[5] == p[5] == (column.references is not None)  # references
                # default presence: sqlite renders any non-None; pg omits it for
                # integer PKs (identity supplies the value).
                assert s[4] == (column.default is not None)
                assert p[4] == (
                    column.default is not None and not (column.primary_key and column.kind == "INTEGER")
                )


def test_indexes_render_zero_diff() -> None:
    for migration in MIGRATIONS:
        for op in migration.ops:
            if not isinstance(op, CreateIndex):
                continue
            s = _parse_index(render_sqlite(op))
            p = _parse_index(render_postgres(op))
            assert s == (op.unique, op.name, op.table, op.columns)
            assert p == s


def test_add_columns_render_zero_diff() -> None:
    for migration in MIGRATIONS:
        for op in migration.ops:
            if not isinstance(op, AddColumn):
                continue
            sqlite_clause = render_sqlite(op).split("ADD COLUMN ")[1]
            pg_clause = render_postgres(op).split("ADD COLUMN ", 1)[1]
            if pg_clause.upper().startswith("IF NOT EXISTS "):
                pg_clause = pg_clause[len("IF NOT EXISTS ") :]
            s = _parse_column_clause(sqlite_clause)
            p = _parse_column_clause(pg_clause)
            assert s[0] == p[0] == op.column.name
            assert s[1] == _expected_sqlite_kind(op.column.kind)
            assert p[1] == _expected_pg_kind(op.column.kind)
            assert s[2] == p[2] == op.column.primary_key
            assert s[3] == p[3] == op.column.not_null


def test_triggers_exist_on_both_dialects() -> None:
    """The append-only audit barrier is a parity item, not a sqlite extra."""
    for migration in MIGRATIONS:
        for op in migration.ops:
            if not isinstance(op, AddTrigger):
                continue
            sql = render_sqlite(op)
            pg = render_postgres(op)
            assert op.table in sql and op.timing in sql and op.event in sql
            assert op.table in pg and op.timing in pg and op.event in pg
            assert op.pg_action, f"{op.name}: pg_action is required for the Postgres arm"


